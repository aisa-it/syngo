-- 0011_event_signatures: подписи событий, полученных по федерации.
--
-- Подписи нельзя пересчитать: событие подписывает сервер-источник. Без их хранения
-- мы не можем отдать чужое событие другому пиру (send_join/state/backfill) — он
-- обязан проверить подпись, а мы вынуждены были отдавать событие без signatures.
ALTER TABLE events ADD COLUMN IF NOT EXISTS signatures jsonb;
